import AppKit
import Observation

/// State and actions for the Setup section of Settings: Accessibility, launch at login, AeroSpace.
@MainActor
@Observable
public final class OnboardingModel {
    public private(set) var accessibilityGranted = false
    public private(set) var loginItem = LoginItemStatus.unavailable
    public private(set) var aeroSpace = AeroSpaceSetup.State.notFound
    /// Result of the last action, shown under the Setup section.
    public private(set) var message: String?
    public private(set) var isUpdatingAeroSpace = false

    @ObservationIgnored private let accessibility: any AccessibilityPlatform
    @ObservationIgnored private let loginItems: any LoginItemService
    @ObservationIgnored private let setup: AeroSpaceSetup
    @ObservationIgnored private let performer: any NotificationActionPerforming
    @ObservationIgnored private let copy: @MainActor (String) -> Void
    @ObservationIgnored private let onAeroSpaceUpdated: @MainActor () -> Void

    public init(
        accessibility: any AccessibilityPlatform,
        loginItems: any LoginItemService,
        setup: AeroSpaceSetup,
        performer: any NotificationActionPerforming,
        copy: @escaping @MainActor (String) -> Void = OnboardingModel.copyToPasteboard,
        onAeroSpaceUpdated: @escaping @MainActor () -> Void = {}
    ) {
        self.accessibility = accessibility
        self.loginItems = loginItems
        self.setup = setup
        self.performer = performer
        self.copy = copy
        self.onAeroSpaceUpdated = onAeroSpaceUpdated
        refresh()
    }

    public func refresh() {
        accessibilityGranted = accessibility.isTrusted(prompt: false)
        loginItem = loginItems.status
        aeroSpace = setup.state()
    }

    /// Shows the system prompt when macOS still allows it, and opens the Accessibility pane.
    public func requestAccessibility() {
        _ = accessibility.isTrusted(prompt: true)
        performer.perform(.open(SidebarModel.accessibilitySettingsURL))
        refresh()
    }

    public func addLoginItem() {
        do {
            try loginItems.register()
            message = loginItems.status == .requiresApproval
                ? "Allow AerospaceSidebar in System Settings › General › Login Items."
                : "AerospaceSidebar opens at login."
        } catch {
            message = "Cannot add the login item: \(error.localizedDescription)"
        }
        refresh()
    }

    public func removeLoginItem() {
        do {
            try loginItems.unregister()
            message = "AerospaceSidebar no longer opens at login."
        } catch {
            message = "Cannot remove the login item: \(error.localizedDescription)"
        }
        refresh()
    }

    public func openLoginItemsSettings() {
        loginItems.openSystemSettings()
    }

    public func updateAeroSpace() async {
        isUpdatingAeroSpace = true
        defer { isUpdatingAeroSpace = false }
        do {
            switch try await setup.apply() {
            case .updated(let backup):
                message = "Updated and reloaded AeroSpace. The previous config is in \(backup.lastPathComponent)."
            case .updatedWithoutReload(let backup):
                message = "Updated the config (previous one in \(backup.lastPathComponent)), but the aerospace command was not found. Reload AeroSpace yourself."
            }
            onAeroSpaceUpdated()
        } catch {
            message = Self.describe(error)
        }
        refresh()
    }

    /// Copies the TOML to add by hand.
    public func copySnippet() {
        copy(Self.snippet)
        message = "Copied the AeroSpace settings. Add them to your AeroSpace config and run `aerospace reload-config`."
    }

    public func revealAeroSpaceConfig() {
        if case .ready(_, let url) = aeroSpace {
            performer.perform(.open(url.deletingLastPathComponent()))
        }
    }

    public static let snippet = """
        [gaps]
        outer.right = [{ monitor.main = \(AeroSpaceSetup.defaultWidth) }, 0]

        \(AeroSpaceConfigEditor.floatRule)

        """

    public static func copyToPasteboard(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    static func describe(_ error: AeroSpaceSetup.SetupError) -> String {
        switch error {
        case .notFound:
            "No AeroSpace config found. Create ~/.config/aerospace/aerospace.toml from AeroSpace's default config first."
        case .generated(let url):
            "\(url.lastPathComponent) is generated by another tool. Add the settings to its source instead (Copy Settings)."
        case .unsupported(let reason):
            "Cannot edit the config automatically: \(reason). Add the settings by hand (Copy Settings)."
        case .rejected(let output):
            "AeroSpace rejected the change, so the original config was restored: \(output)"
        case .io(let reason):
            "Cannot update the config: \(reason)"
        }
    }
}
